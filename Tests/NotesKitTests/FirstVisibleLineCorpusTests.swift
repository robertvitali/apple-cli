    @Test("no quadratic shape on the post-write path")
    func noQuadraticOnPostWritePath() {
        // ABSOLUTE bounds, deliberately not a ratio. The ratio form measured ~40 ms against
        // ~40 ms and review clocked it failing 10 runs in 60 under load — a quotient of two
        // small timings is noise-dominated, and a flaky perf assertion trains people to re-run
        // until green. Each bound below has >100x headroom while still catching its regression
        // by >10x, because the failure modes are catastrophic rather than marginal.
        //
        // NOTE these regressions are invisible to BOTH correctness suites: reverting either one
        // scores 0/57 golden and 0/1417 corpus, because they change only time, not output. That
        // is the entire reason a timing assertion lives in the logic tier at all.
        func time(_ body: String) -> TimeInterval {
            let started = Date()
            _ = NotesText.firstVisibleHtmlLine(body)
            return Date().timeIntervalSince(started)
        }
        _ = time("<script>warmup</script>")

        // (a) the script/style scanner's bail-out. `<script` repeated with no `>` ANYWHERE is
        // the shape that blew up; bare `<` is not, because it never matches a tag name and so
        // takes the cheap reject path — review caught me benchmarking exactly that wrong shape.
        // 50k repeats (~342 KiB), not the full 1 MiB ARG_MAX payload: reverting the bail-out
        // makes the 1 MiB case take ~8 MINUTES to fail, which is miserable CI feedback for a
        // regression that is already unmistakable at a third the size. 50k separates by >10x
        // and fails in about a minute.
        let unclosedTagName = time(String(repeating: "<script", count: 50_000))
        #expect(unclosedTagName < 5.0,
                "342 KiB of `<script` took \(unclosedTagName)s; pre-bail-out this was ~55 s")

        // (b) the `<br>` whitespace class. Two adjacent unbounded quantifiers around `/?` is
        // polynomial backtracking; the possessive form is flat. Pre-fix this measured 0.28 s at
        // 8 KiB and could exhaust the stack outright at larger sizes.
        let brWhitespaceRun = time("<div>a<br" + String(repeating: " ", count: 64 * 1024) + "x</div>")
        #expect(brWhitespaceRun < 5.0,
                "64 KiB whitespace run after `<br` took \(brWhitespaceRun)s; pre-fix this was minutes")
    }

