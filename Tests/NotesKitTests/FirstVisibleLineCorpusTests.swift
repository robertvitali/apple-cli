            return n
        }

        // ICU full case folding maps U+017F onto `s` and U+212A onto `k`, so an ASCII-only
        // `(script|style)` / `[A-Za-z0-9_]` silently widens. Must appear right after a tag name.
        let tagNameTerminator = count { html in
            let lower = html.lowercased()
            for name in ["script", "style"] {
                var search = lower.startIndex
                while let r = lower.range(of: "<" + name, range: search..<lower.endIndex) {
                    let after = r.upperBound
                    if after < html.endIndex {
                        let scalars = String(html[after...]).unicodeScalars
                        if let f = scalars.first, f.value == 0x17F || f.value == 0x212A { return true }
                    }
                    search = r.upperBound
                }
            }
            return false
        }
        #expect(tagNameTerminator > 150, "reach: U+017F/U+212A in the tag-name terminator position (\(tagNameTerminator))")

        // JS `\s` includes U+FEFF and EXCLUDES U+0085; ICU's does the opposite. Must appear
        // inside a `<br …>` for the BREAK_RE class to be exercised.
        let brWhitespace = count { $0.contains("<br\u{feff}") || $0.contains("<br\u{85}") || $0.contains("<br \u{feff}") }
        #expect(brWhitespace > 200, "reach: U+FEFF/U+0085 inside <br> (\(brWhitespace))")

        // ICU `$` matches before a FINAL line terminator; JS `$` without `m` does not.
        let trailingTerminator = count { html in
            guard let last = html.unicodeScalars.last else { return false }
            return [0x0A, 0x0D, 0x85, 0x2028, 0x2029, 0x0B, 0x0C].contains(Int(last.value))
        }
        #expect(trailingTerminator > 100, "reach: trailing line terminator (\(trailingTerminator))")

        // The script/style fixed point is load-bearing only when removing a block SPLICES a new
        // tag out of its neighbours, which needs FRAGMENTS, not whole tokens. The obvious
        // predicate is a trap: `"<script>".contains("scr")` is true, so counting raw substrings
        // scores ~967 while the genuine-fragment rows number far fewer — delete every real splice
        // row and the control would still pass. Strip whole tags FIRST, then look for fragments.
        let spliceFragments = count { html in
            let stripped = html.replacingOccurrences(
                of: "</?(script|style)\\b[^>]*>", with: "", options: [.regularExpression, .caseInsensitive])
            return stripped.contains("scr") || stripped.contains("ipt") || stripped.contains("sty")
        }
        #expect(spliceFragments > 400, "reach: TRUE splice fragments, whole tags removed (\(spliceFragments))")

        let entities = count { $0.contains("&") }
        #expect(entities > 100, "reach: entity decoding (\(entities))")

        // A corpus of only-renders-nothing inputs would pass trivially; assert both outcomes.
        let nilResults = Self.corpus.lazy.filter { $0.1 == nil }.count
        #expect(nilResults > 100, "reach: bodies that render nothing (\(nilResults))")
        #expect(Self.corpus.count - nilResults > 100, "reach: bodies that do render")
    }
